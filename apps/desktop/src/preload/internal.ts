/**
 * The preload for Chord's internal pages (ARCHITECTURE.md §8): Settings sees
 * settings and one chord's theme, never tabs or history.
 */
import type { SettingsApi } from '@chord/ipc';
import { contextBridge } from 'electron';
import { invoke, subscribe, systemApi } from './bridge';

const api: SettingsApi = {
  system: systemApi,
  settings: {
    snapshot: () => invoke('settings:snapshot'),
    onChange: (listener) => subscribe('settings:changed', listener),
    onSection: (listener) => subscribe('settings:section', listener),
    set: (patch) => invoke('settings:set', patch),
    theme: (chordId, theme) => invoke('settings:theme', { chordId, theme }),
    saveTheme: (theme) => invoke('settings:saveTheme', { theme }),
    deleteTheme: (id) => invoke('settings:deleteTheme', { id }),
    copyText: (text) => invoke('settings:copyText', { text }),
    recordingShortcut: (recording) => invoke('settings:recordingShortcut', { recording }),
    chordSignIns: (chordId, separate) => invoke('settings:chordSignIns', { chordId, separate }),
    chordProxy: (chordId, proxy) => invoke('settings:chordProxy', { chordId, proxy }),
    sitePermission: (origin, permission, decision) => invoke('settings:sitePermission', { origin, permission, decision }),
    forgetSite: (origin) => invoke('settings:forgetSite', { origin }),
    linkRoute: (host, chordId) => invoke('settings:linkRoute', { host, chordId }),
    defaultBrowser: () => invoke('settings:defaultBrowser'),
    assistant: (request) => invoke('settings:assistant', request),
    agents: (request) => invoke('settings:agents', request),
    onAgentsChange: (listener) => subscribe('settings:agentsChanged', () => listener()),
    makeDefaultBrowser: () => invoke('settings:makeDefaultBrowser'),
    updateStatus: () => invoke('settings:updateStatus'),
    checkForUpdates: () => invoke('settings:checkForUpdates'),
    restartToUpdate: () => invoke('update:restart'),
    about: () => invoke('settings:about'),
    openUrl: (url) => invoke('settings:openUrl', { url }),
    safeBrowsing: () => invoke('safeBrowsing:status'),
    adBlocking: () => invoke('adBlocking:status'),
    player: () => invoke('settings:player'),
    installPlayer: () => invoke('settings:installPlayer'),
    removePlayer: () => invoke('settings:removePlayer'),
    effects: (change) => invoke('settings:effects', change),
  },
  extensions: {
    install: (input) => invoke('extensions:install', { input }),
    remove: (profileId, id) => invoke('extensions:remove', { profileId, id }),
    options: (profileId, id) => invoke('extensions:options', { profileId, id }),
    update: () => invoke('extensions:update'),
  },
  imports: {
    sources: () => invoke('import:sources'),
    preview: (key) => invoke('import:preview', { key }),
    run: (key, choices) => invoke('import:run', { key, choices }),
    undo: (importId) => invoke('import:undo', { importId }),
    openAccess: () => invoke('import:openAccess'),
    onProgress: (listener) => subscribe('import:progress', listener),
  },
  exports: {
    counts: () => invoke('export:counts'),
    run: (request) => invoke('export:run', request),
    show: (exportId) => invoke('export:show', { exportId }),
    onProgress: (listener) => subscribe('export:progress', listener),
  },
  files: {
    choose: () => invoke('importFile:choose'),
    open: (fileId, passphrase) => invoke('importFile:open', { fileId, passphrase }),
    run: (fileId, choices) => invoke('importFile:run', { fileId, choices }),
    undo: (importId) => invoke('importFile:undo', { importId }),
    onProgress: (listener) => subscribe('importFile:progress', listener),
  },
  sync: {
    status: () => invoke('sync:status'),
    chooseFolder: () => invoke('sync:chooseFolder'),
    setup: (folderId, passphrase) => invoke('sync:setup', { folderId, passphrase }),
    join: (folderId, passphrase) => invoke('sync:join', { folderId, passphrase }),
    choose: (mode) => invoke('sync:choose', { mode }),
    unlock: (passphrase) => invoke('sync:unlock', { passphrase }),
    changePassphrase: (passphrase) => invoke('sync:passphrase', { passphrase }),
    off: () => invoke('sync:off'),
    remove: (device) => invoke('sync:remove', { device }),
    undo: (token) => invoke('sync:undo', { token }),
    rename: (name) => invoke('sync:rename', { name }),
    pause: (paused) => invoke('sync:pause', { paused }),
    relocate: () => invoke('sync:relocate'),
    startOver: (passphrase) => invoke('sync:startOver', { passphrase }),
    rememberKey: (on) => invoke('sync:rememberKey', { on }),
    onStatus: (listener) => subscribe('sync:status', listener),
  },
  passwords: {
    view: () => invoke('passwords:view'),
    setup: (passphrase) => invoke('passwords:setup', { passphrase }),
    unlock: (passphrase) => invoke('passwords:unlock', { passphrase }),
    lock: () => invoke('passwords:lock'),
    keep: (on, passphrase) => invoke('passwords:keep', passphrase === undefined ? { on } : { on, passphrase }),
    changePassphrase: (current, next) => invoke('passwords:passphrase', { current, next }),
    reveal: (id, passphrase) => invoke('passwords:reveal', passphrase === undefined ? { id } : { id, passphrase }),
    copy: (id, passphrase) => invoke('passwords:copy', passphrase === undefined ? { id } : { id, passphrase }),
    add: (login) => invoke('passwords:add', login),
    edit: (id, patch, passphrase) => invoke('passwords:edit', passphrase === undefined ? { id, patch } : { id, patch, passphrase }),
    remove: (id) => invoke('passwords:delete', { id }),
    undo: (id) => invoke('passwords:undelete', { id }),
    forgetNever: (site) => invoke('passwords:forgetNever', { site }),
    startOver: () => invoke('passwords:startOver'),
    importChoose: () => invoke('passwords:importChoose'),
    importPreview: (stageId) => invoke('passwords:importPreview', { stageId }),
    importRun: (stageId, choices, passphrase) => invoke('passwords:importRun', { stageId, choices, ...(passphrase !== undefined ? { passphrase } : {}) }),
    importDrop: (stageId) => invoke('passwords:importDrop', { stageId }),
    importUndo: (importId) => invoke('passwords:importUndo', { importId }),
    exportCsv: (passphrase) => invoke('passwords:export', passphrase !== undefined ? { passphrase } : {}),
    exportShow: (exportId) => invoke('passwords:exportShow', { exportId }),
    count: () => invoke('passwords:count'),
    onImportProgress: (listener) => subscribe('passwords:importProgress', listener),
    changeOnSite: (id) => invoke('passwords:changeOnSite', { id }),
    onChange: (listener) => subscribe('passwords:changed', listener),
  },
};

contextBridge.exposeInMainWorld('chord', Object.freeze(api));
